package pagent

import (
	"context"
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/MunifTanjim/argus/internal/agentgit"
)

// GeneratedMarker marks instruction files that Argus wrote.
const GeneratedMarker = "<!-- generated by argus -->"

var instructionFiles = []string{"CLAUDE.md", "AGENTS.md"}

// Scaffold creates the agent directory layout and commits it. It is safe to
// run on an existing agent directory: it only adds what is missing and keeps
// the existing definition.
func Scaffold(ctx context.Context, dir string, def *Definition, gitMode string, commitFiles bool) (*agentgit.Repo, error) {
	for _, sub := range []string{"memory/topics", "memory/log", "skills", "routines", "files"} {
		if err := os.MkdirAll(filepath.Join(dir, sub), 0o755); err != nil {
			return nil, err
		}
	}
	if existing, err := LoadDefinition(dir); err == nil {
		def = existing
	} else if errors.Is(err, os.ErrNotExist) {
		if def.ID == "" {
			def.ID = NewID()
		}
		if err := def.Save(dir); err != nil {
			return nil, err
		}
	} else {
		return nil, err
	}
	for _, f := range []string{"memory/MEMORY.md", "memory/USER.md"} {
		p := filepath.Join(dir, f)
		if _, err := os.Stat(p); errors.Is(err, os.ErrNotExist) {
			if err := os.WriteFile(p, nil, 0o644); err != nil {
				return nil, err
			}
		} else if err != nil {
			return nil, err
		}
	}

	repo, err := agentgit.Open(ctx, dir, gitMode)
	if err != nil {
		return nil, err
	}
	exclude := slices.Clone(instructionFiles)
	// Git does not track empty directories, and rejects them as pathspecs.
	paths := []string{DefinitionFile, "memory"}
	tracked := []string{"skills", "routines"}
	if commitFiles {
		tracked = append(tracked, "files")
	} else {
		exclude = append(exclude, "files/")
	}
	for _, sub := range tracked {
		if hasFiles(filepath.Join(dir, sub)) {
			paths = append(paths, sub)
		}
	}
	if err := repo.EnsureExcluded(ctx, exclude); err != nil {
		return nil, err
	}
	if !repo.Outer {
		paths = append(paths, ".gitignore")
	}
	_, err = repo.CommitPaths(ctx, "agent: create "+def.Name, []agentgit.Trailer{
		{Key: "Argus-Agent", Value: def.Name},
		{Key: "Argus-Agent-Id", Value: def.ID},
		{Key: "Argus-Source", Value: "you"},
	}, paths, true)
	if err != nil {
		return nil, err
	}
	return repo, nil
}

// ImportInstructionFile returns the content of a hand-written CLAUDE.md or
// AGENTS.md in dir, skipping files that Argus generated.
func ImportInstructionFile(dir string) (string, bool, error) {
	for _, name := range instructionFiles {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return "", false, err
		}
		s := string(data)
		if strings.Contains(s, GeneratedMarker) || strings.TrimSpace(s) == "" {
			continue
		}
		return s, true, nil
	}
	return "", false, nil
}

func hasFiles(dir string) bool {
	found := false
	_ = filepath.WalkDir(dir, func(_ string, e fs.DirEntry, err error) error {
		if err == nil && !e.IsDir() {
			found = true
			return fs.SkipAll
		}
		return nil
	})
	return found
}
