func TestInstructionFileName(t *testing.T) {
	if got := InstructionFileName("claude"); got != "CLAUDE.md" {
		t.Fatalf("claude: %q", got)
	}
	for _, cli := range []string{"codex", "pi", ""} {
		if got := InstructionFileName(cli); got != "AGENTS.md" {
			t.Fatalf("%q: %q", cli, got)
		}
	}
}

func TestRenderOrderAndMarker(t *testing.T) {
	in := InstructionInput{
		Def:        &Definition{Instructions: "INSTR", Workdirs: []string{"/a", "/b"}},
		Settings:   Settings{Timezone: "UTC"},
		Profile:    "PROFILETEXT",
		User:       "USERTEXT",
		Memory:     "MEMORYTEXT",
		Topics:     []string{"topics/go.md"},
		LogLines:   []string{"LOGLINE"},
		Now:        time.Date(2026, 11, 22, 10, 0, 0, 0, time.UTC),
		CoreBudget: 24 * 1024,
		RunSection: "RUNSECTION",
	}
	out := RenderInstructions(in)
	if !strings.HasPrefix(out, "<!-- generated by argus -->\n") {
		t.Fatalf("marker missing:\n%s", out)
	}
	order := []string{"INSTR", "PROFILETEXT", "USERTEXT", "Memory (1 KB of 24 KB)", "MEMORYTEXT",
		"topics/go.md", "LOGLINE", "Current date: 2026-11-22 (UTC)", "You may work in: /a, /b",
		"Never store credentials", "RUNSECTION"}
	last := -1
	for _, s := range order {
		i := strings.Index(out, s)
		if i < 0 {
			t.Fatalf("missing %q:\n%s", s, out)
		}
		if i < last {
			t.Fatalf("%q out of order:\n%s", s, out)
		}
		last = i
	}
}

func TestRenderTruncatesMemoryToBudget(t *testing.T) {
	line := strings.Repeat("x", 99) + "\n"
	mem := strings.Repeat(line, 50) // 5000 bytes
	in := InstructionInput{
		Def:        &Definition{},
		Settings:   Settings{Timezone: "UTC"},
		Memory:     mem,
		Now:        time.Now(),
		CoreBudget: 1024,
	}
	out := RenderInstructions(in)
	if !strings.Contains(out, "(memory truncated: 4 KB over budget)") {
		t.Fatalf("no truncation note:\n%s", out)
	}
	if n := strings.Count(out, line); n != 10 {
		t.Fatalf("kept %d lines, want 10 (cut at line boundary)", n)
	}
	if !strings.Contains(out, "Memory (5 KB of 1 KB)") {
		t.Fatalf("header:\n%s", out)
	}
}

func TestGatherReadsLastLogLines(t *testing.T) {
	dir := t.TempDir()
	profileDir := t.TempDir()
	mk := func(p, c string) {
		full := filepath.Join(dir, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(c), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	mk("memory/MEMORY.md", "mem")
	mk("memory/USER.md", "usr")
	mk("memory/topics/b.md", "")
	mk("memory/topics/a.md", "")
	mk("memory/log/2026-10.md", "old1\nold2\n")
	mk("memory/log/2026-11.md", "l1\nl2\n\nl3\nl4\n")
	if err := os.WriteFile(filepath.Join(profileDir, "PROFILE.md"), []byte("prof"), 0o644); err != nil {
		t.Fatal(err)
	}
	def := &Definition{Instructions: "i"}
	now := time.Now()
	in, err := GatherInput(dir, def, Settings{}, profileDir, 3, 100, now)
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(in.LogLines, "|"); got != "l2|l3|l4" {
		t.Fatalf("log lines: %q", got)
	}
	if in.Memory != "mem" || in.User != "usr" || in.Profile != "prof" {
		t.Fatalf("files: %+v", in)
	}
	if strings.Join(in.Topics, ",") != "a.md,b.md" {
		t.Fatalf("topics: %v", in.Topics)
	}
	if in.CoreBudget != 100 || in.Def != def {
		t.Fatalf("fields: %+v", in)
	}

	empty, err := GatherInput(t.TempDir(), def, Settings{}, "", 3, 100, now)
	if err != nil {
		t.Fatal(err)
	}
	if empty.Memory != "" || len(empty.LogLines) != 0 {
		t.Fatalf("empty: %+v", empty)
	}
}

func TestWriteInstructions(t *testing.T) {
	dir := t.TempDir()
	in := InstructionInput{Def: &Definition{Instructions: "hello"}, Settings: Settings{Timezone: "UTC"}, Now: time.Now()}
	if err := WriteInstructions(context.Background(), dir, "claude", in); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(filepath.Join(dir, "CLAUDE.md"))
	if err != nil || !strings.Contains(string(data), "hello") {
		t.Fatalf("%v %q", err, data)
	}
}
